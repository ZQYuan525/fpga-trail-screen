"""Generate rtl/scene_art_rom.v and tb/scene_{logo,grass}.hex for scene_overlay.

Logo: maintenance/assets/anlogic_logo_cn.png keyed on
white and resized to 192x48 at 2 bpp (0 plate, 1 navy, 2 red) in one BRAM32K.
Word address = row*32 + column/8; pixel j of a word sits in bits [2j+1:2j].

Grass: a 320x72 tile drawn here from a fixed seed (clumps of tapered, bending
blades, a few seed ears) and repeated twice across the screen. Each pixel holds
its position along its own blade, 0 (root) .. 14 (tip), or 15 for no grass; the
overlay shows a pixel when that position is below the growth level of its
column. Word address = row*80 + column/4; pixel j sits in bits [4j+3:4j];
three BRAM32K selected by address[12:11].

Usage: python maintenance/make_scene_art.py [--preview out.png]
"""
import argparse
import random
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
LOGO_SRC = ROOT / "maintenance" / "assets" / "anlogic_logo_cn.png"
LOGO_W, LOGO_H, LOGO_STRIDE = 192, 48, 32
GRASS_W, GRASS_H, GRASS_STRIDE, EMPTY = 320, 72, 80, 15
NAVY, RED = (0x06, 0x1A, 0x3D), (0xC7, 0x06, 0x14)  # sampled from the source
GRASS_COLOURS = [(0x12, 0x20, 0x16), (0x28, 0x42, 0x2A), (0x4E, 0x70, 0x42), (0x84, 0xA2, 0x60), (0xC4, 0xCC, 0x80)]


def logo_pixels() -> list[list[int]]:
    source = Image.open(LOGO_SRC).convert("RGBA")
    flat = Image.alpha_composite(Image.new("RGBA", source.size, (255, 255, 255, 255)), source).convert("RGB")
    image = flat.resize((LOGO_W, LOGO_H), Image.LANCZOS)
    rows = []
    for y in range(LOGO_H):
        row = []
        for x in range(LOGO_W):
            r, g, b = image.getpixel((x, y))
            row.append(0 if min(r, g, b) > 150 else 2 if r > g + 70 else 1)
        rows.append(row)
    return rows


def grass_pixels(seed: int = 5) -> list[list[int]]:
    rng = random.Random(seed)
    frac = [[16] * GRASS_W for _ in range(GRASS_H)]
    blades = []
    x = 0
    while x < GRASS_W:  # clumps of 2-6 blades with uneven gaps
        cx = x + rng.randint(0, 6)
        for _ in range(rng.randint(2, 6)):
            blades.append((cx + rng.randint(-3, 3),
                           rng.choice([rng.randint(12, 30), rng.randint(24, 50), rng.randint(40, 70)]),
                           rng.uniform(-1, 1) * rng.choice([0.3, 0.6, 1.0, 1.3]), rng.random() < 0.08))
        x = cx + rng.randint(5, 16)
    blades.sort(key=lambda b: -b[1])  # tall blades behind
    for rx, length, bend, ear in blades:
        w0 = 2 if length > 20 else 1
        for k in range(length):
            f = k / length
            xo = rx + bend * length * 0.6 * f * f  # curls over near the tip
            w = max(1, round(w0 * (1 - f) + 0.4))
            fy = GRASS_H - 1 - int(k * (1 - 0.25 * abs(bend) * f))
            q = min(14, int(f * 16))
            for dx in range(w):
                xx = (int(round(xo)) + dx) % GRASS_W  # wrap so the two copies join
                if 0 <= fy < GRASS_H and q <= frac[fy][xx]:
                    frac[fy][xx] = q
        if ear and length > 30:
            tx = int(round(rx + bend * length * 0.6)) % GRASS_W
            ty = GRASS_H - 1 - int(length * (1 - 0.25 * abs(bend)))
            for dy in range(-5, 1):
                for dx in ((0, 1) if dy > -5 else (0,)):
                    if 0 <= ty + dy < GRASS_H:
                        frac[ty + dy][(tx + dx) % GRASS_W] = 14
    return [[EMPTY if q > 14 else q for q in row] for row in frac]


def pack(rows, width, stride, bits, depth):
    memory = [0] * depth
    per = 16 // bits
    for y, row in enumerate(rows):
        for w in range(width // per):
            memory[y * stride + w] = sum(row[w * per + j] << (bits * j) for j in range(per))
    return memory


def bram(name: str, memory: list[int]) -> str:
    inits = []
    for n in range(128):
        value = "".join(f"{memory[n * 16 + k]:04x}" for k in reversed(range(16)))
        inits.append(f"        .INIT_{n:02X}(256'h{value})")
    return ("    EG_PHY_BRAM32K #(\n"
            "        .MODE(\"SP16K\"),.DATA_WIDTH_A(\"16\"),.DATA_WIDTH_B(\"16\"),.REGMODE_A(\"NOREG\"),\n"
            "        .CSAMUX(\"1\"),.OCEAMUX(\"1\"),.RSTAMUX(\"0\"),.WEAMUX(\"0\"),\n"
            + ",\n".join(inits) + "\n"
            f"    ) {name}(.doa({name}_data),.dia(16'd0),.addra(addr[10:0]),.bytea(1'b0),.bytewea(1'b0),\n"
            "        .csa(1'b1),.wea(1'b0),.clka(clk),.rsta(1'b0),.ocea(1'b1),\n"
            "        .dob(),.dib(16'd0),.addrb(11'd0),.byteb(1'b0),.byteweb(1'b0),\n"
            "        .csb(1'b0),.web(1'b0),.clkb(1'b0),.rstb(1'b0),.oceb(1'b0));\n")


def verilog(logo: list[int], grass: list[int]) -> str:
    return (
        "`timescale 1ns/1ps\n"
        "// Scene artwork for scene_overlay. Generated by maintenance/make_scene_art.py;\n"
        "// do not edit by hand.\n\n"
        "// Logo 192x48 at 2 bpp (0 plate, 1 navy, 2 red): address = row*32 + column/8,\n"
        "// pixel j of a word is data[2j+1:2j].\n"
        "module scene_logo_rom(input wire clk,input wire [10:0] addr,output wire [15:0] data);\n"
        "    wire [15:0] u_rom_data;\n"
        "    assign data=u_rom_data;\n"
        + bram("u_rom", logo) +
        "endmodule\n\n"
        "// Grass tile 320x72, 4 bits per pixel (blade position 0..14, 15 none):\n"
        "// address = row*80 + column/4, pixel j of a word is data[4j+3:4j].\n"
        "module scene_grass_rom(input wire clk,input wire [12:0] addr,output wire [15:0] data);\n"
        "    wire [15:0] u_rom0_data,u_rom1_data,u_rom2_data;\n"
        "    reg [1:0] bank;\n"
        "    always @(posedge clk) bank<=addr[12:11];\n"
        "    assign data=bank==0?u_rom0_data:bank==1?u_rom1_data:u_rom2_data;\n"
        + "".join(bram(f"u_rom{b}", grass[b * 2048:(b + 1) * 2048]) for b in range(3)) +
        "endmodule\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--preview", type=Path, help="write a 3x enlarged logo + full-growth grass preview PNG")
    args = parser.parse_args()
    logo_rows, grass_rows = logo_pixels(), grass_pixels()
    logo = pack(logo_rows, LOGO_W, LOGO_STRIDE, 2, 2048)
    grass = pack(grass_rows, GRASS_W, GRASS_STRIDE, 4, 3 * 2048)
    (ROOT / "rtl" / "scene_art_rom.v").write_bytes(verilog(logo, grass).encode())
    (ROOT / "tb" / "scene_logo.hex").write_bytes("".join(f"{w:04x}\n" for w in logo).encode())
    (ROOT / "tb" / "scene_grass.hex").write_bytes("".join(f"{w:04x}\n" for w in grass).encode())
    if args.preview:
        out = Image.new("RGB", (GRASS_W, LOGO_H + 8 + GRASS_H), (40, 40, 40))
        for y, row in enumerate(logo_rows):
            for x, c in enumerate(row):
                out.putpixel((x, y), [(255, 255, 255), NAVY, RED][c])
        for y, row in enumerate(grass_rows):
            for x, q in enumerate(row):
                if q != EMPTY:
                    out.putpixel((x, LOGO_H + 8 + y), GRASS_COLOURS[q >> 2])
        out.resize((out.width * 3, out.height * 3), Image.NEAREST).save(args.preview)


if __name__ == "__main__":
    main()
