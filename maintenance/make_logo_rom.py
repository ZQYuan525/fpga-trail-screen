"""Generate rtl/logo_rom.v and tb/logo_rom.hex from the Anlogic logo.

Source: a .pptx given with --deck whose member ppt/media/image3.png is the
Anlogic logo. The image is resized
to 160x32 and quantised to 2 bits per pixel: 0 = plate, 1 = navy, 2 = red.
Word address = row*32 + column/8; pixel j of a word sits in bits [2j+1:2j].

Usage: python maintenance/make_logo_rom.py --deck slides.pptx [--preview out.png]
"""
import argparse
import io
import zipfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
MEMBER = "ppt/media/image3.png"
WIDTH, HEIGHT, STRIDE = 160, 32, 32
NAVY, RED = (0x12, 0x20, 0x41), (0xCD, 0x12, 0x20)


def quantise(deck_path: Path) -> list[list[int]]:
    with zipfile.ZipFile(deck_path) as deck:
        source = Image.open(io.BytesIO(deck.read(MEMBER))).convert("RGBA")
    image = source.resize((WIDTH, HEIGHT), Image.LANCZOS)
    rows = []
    for y in range(HEIGHT):
        row = []
        for x in range(WIDTH):
            r, g, _, a = image.getpixel((x, y))
            row.append(0 if a < 110 else 2 if r > g + 60 else 1)
        rows.append(row)
    return rows


def words(rows: list[list[int]]) -> list[int]:
    memory = [0] * (HEIGHT * STRIDE)
    for y, row in enumerate(rows):
        for w in range(WIDTH // 8):
            memory[y * STRIDE + w] = sum(row[w * 8 + j] << (2 * j) for j in range(8))
    return memory


def verilog(memory: list[int]) -> str:
    inits = []
    for n in range(len(memory) // 16):
        value = "".join(f"{memory[n * 16 + k]:04x}" for k in reversed(range(16)))
        inits.append(f"        .INIT_{n:02X}(256'h{value})")
    return (
        "`timescale 1ns/1ps\n"
        "// Official Anlogic logo, 160x32 at 2 bpp (0 plate, 1 navy, 2 red) in one\n"
        "// BRAM32K. Generated by maintenance/make_logo_rom.py; do not edit by hand.\n"
        "// Word address = row*32 + column/8; pixel j of a word is data[2j+1:2j].\n"
        "module logo_rom(\n"
        "    input wire clk,\n"
        "    input wire [9:0] addr,\n"
        "    output wire [15:0] data\n"
        ");\n"
        "    EG_PHY_BRAM32K #(\n"
        "        .MODE(\"SP16K\"),.DATA_WIDTH_A(\"16\"),.DATA_WIDTH_B(\"16\"),.REGMODE_A(\"NOREG\"),\n"
        "        .CSAMUX(\"1\"),.OCEAMUX(\"1\"),.RSTAMUX(\"0\"),.WEAMUX(\"0\"),\n"
        + ",\n".join(inits) + "\n"
        "    ) u_rom(.doa(data),.dia(16'd0),.addra({1'b0,addr}),.bytea(1'b0),.bytewea(1'b0),\n"
        "        .csa(1'b1),.wea(1'b0),.clka(clk),.rsta(1'b0),.ocea(1'b1),\n"
        "        .dob(),.dib(16'd0),.addrb(11'd0),.byteb(1'b0),.byteweb(1'b0),\n"
        "        .csb(1'b0),.web(1'b0),.clkb(1'b0),.rstb(1'b0),.oceb(1'b0));\n"
        "endmodule\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--deck", type=Path, required=True, help="slide deck holding the logo")
    parser.add_argument("--preview", type=Path, help="write a 4x enlarged preview PNG")
    args = parser.parse_args()
    rows = quantise(args.deck)
    memory = words(rows)
    (ROOT / "rtl" / "logo_rom.v").write_bytes(verilog(memory).encode())
    (ROOT / "tb" / "logo_rom.hex").write_bytes("".join(f"{w:04x}\n" for w in memory).encode())
    if args.preview:
        colours = [(255, 255, 255), NAVY, RED]
        out = Image.new("RGB", (WIDTH, HEIGHT))
        out.putdata([colours[c] for row in rows for c in row])
        out.resize((WIDTH * 4, HEIGHT * 4), Image.NEAREST).save(args.preview)


if __name__ == "__main__":
    main()
